"""Export bounded public XNYS session facts; never input market prices or volumes.

Reproduce with the repository Python environment (exchange_calendars == 4.13.2).
Upstream exchange_calendars is Apache-2.0. This is calendar data, not vendor data.
"""

import hashlib
import importlib.metadata
import json
from pathlib import Path

import exchange_calendars


def main() -> None:
    version = importlib.metadata.version("exchange_calendars")
    if version != "4.13.2":
        raise RuntimeError(f"Expected pinned exchange_calendars 4.13.2, found {version}")
    start, end = "2024-01-01", "2027-12-31"
    calendar = exchange_calendars.get_calendar("XNYS", start=start, end=end)
    records = [
        [str(day.date()), row["open"].isoformat().replace("+00:00", "Z"), row["close"].isoformat().replace("+00:00", "Z")]
        for day, row in calendar.schedule.iterrows()
    ]
    digest = hashlib.sha256(json.dumps(records, separators=(",", ":")).encode()).hexdigest()
    target = Path(__file__).resolve().parents[1] / "src/lib/calendars/xnys-sessions.ts"
    target.parent.mkdir(exist_ok=True)
    target.write_text(
        "// Generated by frontend/scripts/export-chart-calendar.py; public XNYS regular-session facts.\n"
        "// Source: exchange_calendars 4.13.2 (Apache-2.0); do not edit by hand.\n"
        f"// Canonical [date,open,close] JSON SHA256: {digest}\n"
        "import type { ChartCalendar } from '../chart-daily-series'\n\n"
        "const sessions = [\n"
        + "".join(f"  {json.dumps(record, separators=(',', ':'))},\n" for record in records)
        + "] as const\n\nexport const xnysChartCalendar: ChartCalendar = {\n"
        + f"  calendarId: 'XNYS', version: 'exchange-calendars:{version}:XNYS', start: '{start}', end: '{end}',\n"
        + "  sessions: sessions.map(([date, open, close]) => ({ date, open, close })),\n}\n",
        encoding="utf-8", newline="\n",
    )
    print(f"{len(records)} public sessions; {target.stat().st_size} bytes; canonical SHA256 {digest}")


if __name__ == "__main__":
    main()
